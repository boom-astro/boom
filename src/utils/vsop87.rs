/// The Earth's position at `jd` (TT) on the FK5 equator of J2000, au, by the
/// rotation VSOP87 publishes for its frame.
pub fn earth_equatorial(jd: f64) -> [f64; 3] {
    let v = series(jd);
    [
        v[0] + 0.000_000_440_360 * v[1] - 0.000_000_190_919 * v[2],
        -0.000_000_479_966 * v[0] + 0.917_482_137_087 * v[1] - 0.397_776_982_902 * v[2],
        0.397_776_982_902 * v[1] + 0.917_482_137_087 * v[2],
    ]
}

fn series(jd: f64) -> [f64; 3] {
    let t = (jd - 2_451_545.0) / 365_250.0;
    SERIES.map(|powers| {
        powers.iter().rev().fold(0.0, |sum, terms| {
            sum * t
                + terms
                    .iter()
                    .map(|[a, b, c]| a * (b + c * t).cos())
                    .sum::<f64>()
        })
    })
}
